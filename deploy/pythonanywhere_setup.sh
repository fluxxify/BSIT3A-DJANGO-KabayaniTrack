#!/usr/bin/env bash
#
# One-command setup for a PythonAnywhere free account.
#
# Usage:
#   git clone https://github.com/fluxxify/BSIT3A-DJANGO-KabayaniTrack.git ~/KabayaniTrack
#   cd ~/KabayaniTrack
#   PA_USERNAME=yourusername bash deploy/pythonanywhere_setup.sh
#
set -euo pipefail

REPO_URL="${REPO_URL:-https://github.com/fluxxify/BSIT3A-DJANGO-KabayaniTrack.git}"
PROJECT_DIR="${PROJECT_DIR:-$HOME/KabayaniTrack}"
PYTHON_BIN="${PYTHON_BIN:-python3.10}"
PA_USERNAME="${PA_USERNAME:-$(whoami)}"
DOMAIN="${PA_USERNAME}.pythonanywhere.com"

if ! command -v "$PYTHON_BIN" >/dev/null 2>&1; then
    echo "ERROR: $PYTHON_BIN was not found." >&2
    echo "Use a Python version available on PythonAnywhere, for example:" >&2
    echo "  PYTHON_BIN=python3.12 PA_USERNAME=$PA_USERNAME bash deploy/pythonanywhere_setup.sh" >&2
    exit 1
fi

if [ ! -d "$PROJECT_DIR/.git" ]; then
    git clone "$REPO_URL" "$PROJECT_DIR"
else
    git -C "$PROJECT_DIR" pull --ff-only
fi

cd "$PROJECT_DIR"

if [ ! -d .venv ]; then
    if ! "$PYTHON_BIN" -m venv .venv; then
        echo "venv failed; falling back to virtualenv..." >&2
        "$PYTHON_BIN" -m pip install --user virtualenv
        "$PYTHON_BIN" -m virtualenv -p "$PYTHON_BIN" .venv
    fi
fi

# shellcheck disable=SC1091
. .venv/bin/activate

python -m pip install --upgrade pip
python -m pip install -r requirements.txt

python manage.py migrate --noinput
python manage.py collectstatic --noinput
python manage.py check

SECRET_KEY="$(python -c 'import secrets; print(secrets.token_urlsafe(50))')"

mkdir -p deploy
cat > deploy/pythonanywhere_wsgi.generated.py <<EOF
"""Generated by deploy/pythonanywhere_setup.sh."""

import os
import sys

project_home = os.path.expanduser('$PROJECT_DIR')
if project_home not in sys.path:
    sys.path.insert(0, project_home)

os.environ['DJANGO_SETTINGS_MODULE'] = 'mysite.settings'
os.environ['DJANGO_DEBUG'] = '0'
os.environ['DJANGO_SECRET_KEY'] = '$SECRET_KEY'
os.environ['DJANGO_ALLOWED_HOSTS'] = '$DOMAIN'
os.environ['DJANGO_CSRF_TRUSTED_ORIGINS'] = 'https://$DOMAIN'

from django.core.wsgi import get_wsgi_application  # noqa: E402

application = get_wsgi_application()
EOF

python manage.py check --deploy || true

cat <<EOF

============================================================
PythonAnywhere setup files are ready.
============================================================

Project:  $PROJECT_DIR
Venv:     $PROJECT_DIR/.venv
Python:   $("$PYTHON_BIN" --version 2>&1)
Domain:   https://$DOMAIN
WSGI:     $PROJECT_DIR/deploy/pythonanywhere_wsgi.generated.py

Next steps on the PythonAnywhere "Web" tab:
  1. Add a new web app -> Manual configuration -> $PYTHON_BIN
  2. Source code:      $PROJECT_DIR
  3. Working directory: $PROJECT_DIR
  4. Virtualenv:       $PROJECT_DIR/.venv
  5. Open the WSGI configuration file and replace its contents with:
       cat $PROJECT_DIR/deploy/pythonanywhere_wsgi.generated.py
  6. Click Reload and open https://$DOMAIN/

Then create an admin account:
  cd $PROJECT_DIR
  source .venv/bin/activate
  python manage.py createsuperuser

Optional sample data after creating the admin:
  python manage.py seed_ofw --user YOUR_ADMIN_USERNAME

EOF

if [ "${CREATE_SUPERUSER:-0}" = "1" ]; then
    python manage.py createsuperuser
fi
